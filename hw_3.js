// Для цього створюємо функцію та використаємо цикл while.
function multiply(x, y)
{
  let result = 1; //назначаємо змінну result яка дорівнює одиниці 
  let i = 0; //назначаємо зміну i для того щоб рахувати цикли

  while (i < y) // створюємо умову до досягнення якої цикл буде виконуватись
{ result = result * x;
    i++;} 

  return result;// повертаємо результат
}

console.log(multiply(2, 3)); // виконуємо функцію.
